# -*- coding: utf-8 -*-
"""Generates docs/benchmark-results.md and docs/failure-gallery.md from the run record (results/runs/*.json) and the stored data.
Numbers get into the text from the data, not from memory: after a new measurement the documents rewrite themselves.
Output is English; a Czech snapshot of the 2026-10-16 version lives in docs/cs/ (not regenerated).
  python tools/make_docs.py            # from the latest run in results/runs/
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import datasets  # noqa: E402
import diagnose  # noqa: E402
import evaluate  # noqa: E402

ROOT = datasets.ROOT
DOCS = ROOT / "docs"
SYS_LABEL = {
    "dense_base": "e5-base, question meaning (local)", "dense_large": "e5-large, question meaning", "bm25_raw": "BM25, lay question",
    "bm25_rewrite": "BM25, rewritten question", "rrf_dense_bm25": "RRF: e5-large + BM25 (no rewrite)",
    "rrf_dense_rewrite": "RRF: e5-large (question + rewrite), no BM25", "rrf_v2": "RRF: e5-large (question + rewrite) + BM25 over the rewrite (v2)",
    "weighted_v2": "weighted sum instead of RRF", "v3_llm_rerank": "v3: v2 + LLM picks 5 of 20 + paragraph rules (final)",
}
ABBREVIATIONS = ("Abbreviations: ZP = Labour Code, ZZ = Employment Act, ZNP = Sickness Insurance Act, NV 590 = Government Decree 590/2006. "
                 "Questions, answers and manual review notes quoted below are in Czech, as in the data files.")


def latest_run() -> dict:
    files = sorted((ROOT / "results" / "runs").glob("*.json"))
    return json.loads(files[-1].read_text(encoding="utf-8"))


def _ci(m: dict) -> str:
    return f"{m['mean']:.2f} ({m['ci95'][0]:.2f}–{m['ci95'][1]:.2f})"


def write_benchmark(rec: dict) -> Path:
    r, cfg, n = rec["run"], rec["config"], rec["n"]
    ret, ans = rec["retrieval"], rec["answers"]
    L = ["[Česky](cs/benchmark-results.md)", "", "# Benchmark results", "", ABBREVIATIONS, "",
         f"Generated by `tools/experiments.py` + `tools/make_docs.py`. Run from commit `{r['git']['commit']}`{' (uncommitted changes)' if r['git']['dirty'] else ''}, "
         f"{r['started']}, {r['mode']}, took {r['runtime_s']} s, cost ${r['cost_usd']:.2f}. Python {r['python']}, numpy {r['numpy']}, {r['platform']}.", "",
         "**What is measured and what is not.** Retrieval is replayed here from stored embeddings and stored LLM answers (rewrite, selection). The retrieval code is therefore verified and the run is repeatable, "
         "but **no new model call was made**. The answers (section 4) come from earlier measurements with manual review. What a section does not say is stated in that section.", "",
         "## 0. Data", "",
         f"{n['questions']} questions: {n['answerable']} with an answer in the laws and {n['questions'] - n['answerable']} deliberately without one (the correct answer is \"I don't know\"). "
         f"Roles of the sets (dev / validation / test) and proof of when they were created: [`data/splits.json`](../data/splits.json), rules in [evaluation-methodology.md](evaluation-methodology.md).", "",
         "| Role | Questions with an answer | Sets |", "|---|---|---|",
         f"| dev | {n['answerable_dev']} | 1–46 (used for tuning) |",
         f"| validation | {n['answerable_validation']} | 47–56 |",
         f"| test | {n['answerable_test']} | 57–66 |", "",
         "Data fingerprints: " + ", ".join(f"`{k}` {v}" for k, v in rec["datasets"].items()), "",
         f"Configuration: embedding `{cfg['embedding']}` (v1 `{cfg['embedding_v1']}`), rewrite and selection `{cfg['llm_rewrite_rerank']}`, answer `{cfg['llm_answer']}`, "
         f"{cfg['n_candidates']} candidates, {cfg['top_k']} chunks for the model, RRF k = {cfg['rrf_k']}. Prompt fingerprints: " + ", ".join(f"{k} `{v}`" for k, v in cfg["prompt_hashes"].items()) + ".", ""]

    # 1) retrieval
    L += ["## 1. Retrieval", "",
          f"A correct chunk among the top k, over all {n['answerable']} questions with an answer. In brackets the 95% confidence interval (bootstrap over questions, 10,000 resamples). "
          "For questions with two correct chunks, Recall is the share found.", "",
          "| System | Recall@1 | Recall@3 | Recall@5 | Recall@10 | Recall@20 | MRR | nDCG@5 |", "|---|---|---|---|---|---|---|---|"]
    for s, lab in SYS_LABEL.items():
        v = ret["all"].get(s)
        if not v:
            continue
        m = v["metrics"]
        mean = {k: (f"{x['mean']:.2f}" if x else "–") for k, x in ((k, m.get(k)) for k in ("recall@1", "recall@3", "recall@10", "recall@20", "ndcg@5"))}
        L.append(f"| {lab} | {mean['recall@1']} | {mean['recall@3']} | {_ci(m['recall@5'])} | {mean['recall@10']} | {mean['recall@20']} | {_ci(m['mrr'])} | {mean['ndcg@5']} |")
    L += ["", "The final system returns only 5 chunks (that is all the model receives), so Recall@10 and @20 are missing for it.", "",
          "### By set role (Recall@5 and MRR)", "",
          "| System | dev (n=%d) R@5 | MRR | validation (n=%d) R@5 | MRR | test (n=%d) R@5 | MRR |" % (n["answerable_dev"], n["answerable_validation"], n["answerable_test"]),
          "|---|---|---|---|---|---|---|"]
    for s, lab in SYS_LABEL.items():
        if s not in ret["all"]:
            continue
        cells = []
        for sp in ("dev", "validation", "test"):
            m = ret[sp][s]["metrics"]
            cells += [f"{m['recall@5']['mean']:.2f}", f"{m['mrr']['mean']:.2f}"]
        L.append(f"| {lab} | " + " | ".join(cells) + " |")
    L += ["", f"**Mind the size.** Test has {n['answerable_test']} and validation {n['answerable_validation']} questions. One question is 12 percentage points, the confidence intervals are wide, "
          "and for 8 out of 8 the lower bound is ~0.68 (Wilson). The dev number is inflated: it was used for tuning. The \"test\" role serves here as a check, not as proof.", ""]

    # 2) ablation
    a = ret["all"]
    gm = lambda s, k: a[s]["metrics"][k]["mean"]
    L += ["## 2. What each part contributes (ablation)", "",
          "Paired comparison on the same questions. \"A better / B better\" = on how many questions A, resp. B, had the higher Recall@5. "
          "p is an exact two-sided sign test: p below 0.05 says the difference is probably not chance. Above that it is only an observation.", "",
          "| Comparison | A better | B better | tie | p |", "|---|---|---|---|---|"]
    names = {"rrf_v2": "RRF v2", "dense_large": "e5-large only", "rrf_dense_bm25": "RRF without rewrite", "rrf_dense_rewrite": "RRF without BM25",
             "weighted_v2": "weighted sum", "v3_llm_rerank": "v3 (LLM selection)", "dense_base": "e5-base"}
    for k, v in rec["paired_tests_recall5_all"].items():
        x, y = k.split(" vs ")
        L.append(f"| {names.get(x, x)} × {names.get(y, y)} | {v['a_better']} | {v['b_better']} | {v['ties']} | {v['p']:.3f} |")
    L += ["", "What follows from this (numbers are from the tables above):", ""]
    L.append(f"- **LLM selection is the only component with a clear benefit.** Recall@1 {gm('rrf_v2', 'recall@1'):.2f} → {gm('v3_llm_rerank', 'recall@1'):.2f}, MRR {gm('rrf_v2', 'mrr'):.2f} → {gm('v3_llm_rerank', 'mrr'):.2f}, "
             f"better on {rec['paired_tests_recall5_all']['v3_llm_rerank vs rrf_v2']['a_better']} questions, worse on {rec['paired_tests_recall5_all']['v3_llm_rerank vs rrf_v2']['b_better']}.")
    L.append(f"- **BM25 did not pay off on these questions.** RRF without BM25 has Recall@5 {gm('rrf_dense_rewrite', 'recall@5'):.2f} and Recall@20 {gm('rrf_dense_rewrite', 'recall@20'):.2f}, "
             f"RRF with BM25 {gm('rrf_v2', 'recall@5'):.2f} and {gm('rrf_v2', 'recall@20'):.2f}. The difference is not statistically significant, but the direction is the opposite of what was expected. "
             "The set contains no questions about exact section numbers and identifiers, which is exactly where BM25 is supposed to be strong. The decision is therefore postponed to a new set (see [limitations.md](limitations.md)).")
    L.append(f"- **The question rewrite does no harm without BM25.** e5-large alone: Recall@5 {gm('dense_large', 'recall@5'):.2f}; with the rewrite: {gm('rrf_dense_rewrite', 'recall@5'):.2f}. The difference is about two questions and cannot be told apart from chance.")
    L.append(f"- **e5-large vs e5-base:** Recall@5 {gm('dense_large', 'recall@5'):.2f} vs {gm('dense_base', 'recall@5'):.2f}." if "dense_base" in a else "- e5-base: skipped (torch or the model is missing).")
    L.append(f"- **A lay question hurts BM25:** {gm('bm25_raw', 'recall@5'):.2f} vs {gm('bm25_rewrite', 'recall@5'):.2f} after the rewrite. Here the rewrite clearly helps (the law says \"mzda\", not \"výplata\"; both are Czech words for pay).")
    L += ["", "### RRF: parameter k", "", "| k | Recall@5 | MRR |", "|---|---|---|"]
    for k, v in rec["rrf_k_sweep"].items():
        L.append(f"| {k}{' (used)' if k == '60' else ''} | {_ci(v['recall@5'])} | {_ci(v['mrr'])} |")
    L += ["", "The value of k barely shows in the result: the intervals overlap. That is why the default 60 stays.", "",
          "### RRF vs weighted score sum", "",
          f"The BM25 weight was chosen on dev questions only (by MRR): **{cfg['weighted_bm25_weight_from_dev']}**. "
          f"On all questions the weighted sum has Recall@5 {gm('weighted_v2', 'recall@5'):.2f} and MRR {gm('weighted_v2', 'mrr'):.2f}, RRF {gm('rrf_v2', 'recall@5'):.2f} and {gm('rrf_v2', 'mrr'):.2f}. "
          f"The difference is not significant (p = {rec['paired_tests_recall5_all']['rrf_v2 vs weighted_v2']['p']:.2f}). RRF stays because it needs no weight tuning and no score normalisation. "
          "The optimal BM25 weight came out very low, which is the same signal as above: keyword matching helps little.", ""]

    # 3) rerank
    rr = rec["rerank"]
    L += ["## 3. Picking 5 of 20: none, cross-encoder, LLM", "",
          f"The same {rr['llm']['n']} questions, the same 20 candidates from RRF. Stored results from `tools/rerank_compare.py` (the cross-encoder ran locally on CPU, {rr['cross_encoder_s_na_otazku_cpu']} s per question). "
          "Hit@5 = at least one correct chunk is among the five selected.", "",
          "| Method | Hit@5 | MRR@5 |", "|---|---|---|"]
    for k in ("rrf5", "ce", "llm"):
        L.append(f"| {rr[k]['label']} | {_ci(rr[k]['hit@5'])} | {_ci(rr[k]['mrr@5'])} |")
    p = rr["paired_llm_vs_ce"]
    L += ["", f"LLM vs cross-encoder: better on {p['a_better']} questions, worse on {p['b_better']}, p = {p['p']:.3f}. "
          "The 56 vs 52 figure in the README therefore shows a direction, but on 56 questions it cannot be considered proven. "
          "The LLM also sees all 20 candidates at once and is paid for on every query. The cross-encoder is free and deterministic, but slow on CPU.", ""]

    # 4) answers
    L += ["## 4. Answers", "",
          "Source: stored runs v1, v2, v3 (v3 = final) and manual review against the text of the law (a second verdict by Claude Opus 5.5, which the project owner went through). "
          "Correctness is a judgement; it cannot be computed by a rule. That is why a deterministic check (the columns on the right), which does not need a judge, is added next to the AI judge and the manual review.", "",
          "| Version | Set | Correct (95% interval) | Needless \"I don't know\" | Correct \"I don't know\" | Answered without a source | Numbers outside cited chunks |", "|---|---|---|---|---|---|---|"]
    for v in ("v1", "v2", "v3"):
        for sp in ("all", "dev", "validation", "test"):
            x = ans[v]["per_split"][sp]
            lab = {"all": "all", "dev": "dev", "validation": "validation", "test": "test"}[sp]
            L.append(f"| {v} | {lab} | {x['correct']} of {x['n']} ({x['correct_ci95'][0]:.2f}–{x['correct_ci95'][1]:.2f}) | {x['false_refusals']} of {x['answerable']} | "
                     f"{x['correct_refusals']} of {x['unanswerable']} | {x['answered_without_source']} of {x['unanswerable']} | {x['det_unsupported_number']} |")
    t = rec["transitions"]
    L += ["", f"**Changes per question.** v1 → v2: fixed {len(t['v1->v2']['fixed'])}, regressed {len(t['v1->v2']['regressed'])} (questions {', '.join(map(str, t['v1->v2']['regressed']))}). "
          f"v2 → v3: fixed {len(t['v2->v3']['fixed'])}, regressed {len(t['v2->v3']['regressed'])}.", "",
          "**What this does not show.** 66 of 66 for v3 is inflated: 56 of these questions were used for tuning. The honest check is the \"test\" row (10 questions, interval lower bound ~0.72), and it alone "
          "does not prove that the system will do the same on new questions. That is why a new set is prepared, to be run once (see [evaluation-methodology.md](evaluation-methodology.md)).", "",
          "**Number check.** The column \"numbers outside cited chunks\" is a suspicion, not an error: a number in the answer that is not in the text of any cited chunk. "
          "The check distinguishes two cases: a number that is in another supplied chunk than the cited one (wrong citation), and a number that is in none (a derived value, e.g. a sum or a half, or invented). "
          "Numbers written in words in the law (\"patnáctidenní\", i.e. fifteen-day) are converted to digits.", ""]
    fl = ans["v3"]["per_split"]["all"].get("flagged", [])
    qtext = {q["id"]: q["q"] for q in datasets.questions()}
    L += [f"Suspicions for v3 ({len(fl)} answers):", "", "| Question | Number in another supplied chunk (wrong citation) | Number in no chunk (derived?) | Cited chunks |", "|---|---|---|---|"]
    L += [f"| {x['id']}: {qtext[x['id']]} | {', '.join(x['misattributed']) or '–'} | {', '.join(x['in_no_chunk']) or '–'} | {x['cited']} |" for x in fl]
    L += ["", "Manual walk-through of these answers: a sum (24 + 11 = 35 hours), a half (20 hours out of 40) and \"from the 15th day\" after 14 days are correct derived values that the answer itself explains, "
          "but they cannot be backed by a citation. **One real citation error:** for question 21, \"11 hours\" is in chunk [4], the answer cites it as [1]. The answer is correct in substance, only the reference points elsewhere. "
          "An AI judge that compares meaning would easily miss this.", ""]

    # 5) operations
    ops = rec["ops"]
    lat = ops["retrieval_compute_latency"]
    L += ["## 5. Operations", "",
          "| Version | Cost per question in the measurement |", "|---|---|"]
    for v, c in ops["cost_per_question_usd"].items():
        L.append(f"| {v} | ${c:.5f} |")
    L += ["", f"{ops['cost_note'][0].upper() + ops['cost_note'][1:]}. The whole project cost about $0.66 including mistakes (see the [hidden-reasoning incident](incidents/2026-10-06-skryte-premysleni.md)).", "",
          f"Time of the retrieval computation itself (matrix × vector, BM25, RRF) from cache: **p50 {lat['p50_ms']} ms, p95 {lat['p95_ms']} ms**, max {lat['max_ms']} ms ({lat['calls']} calls, this computer). "
          f"{ops['latency_note'][0].upper() + ops['latency_note'][1:]}", "",
          "p50/p95/p99 of the whole service, throughput and error rate under load are **not measured**. A load test would run against the paid API and against the $0.75 limit on the key, so it was not done (see [limitations.md](limitations.md)).", ""]

    # 6) regressions
    L += ["## 6. Regressions against the reference state", ""]
    L += ([f"- {x}" for x in rec["regressions"]] if rec.get("regressions") else ["None. The rank of the correct chunks for the final system is the same or better than in `results/baseline.json`."])
    out = DOCS / "benchmark-results.md"
    DOCS.mkdir(exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out


