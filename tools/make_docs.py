def _case(title: str, row: dict, gold: str, cat: list[str], cause: str, fix: str, proof: str) -> list[str]:
    ans = (row.get("answer") or "").strip().replace("\n", " ")
    return [f"### {title}", "",
            f"- **Input:** {row['q']}",
            f"- **Expected behaviour:** {gold}",
            f"- **Actual behaviour:** {ans[:420]}{'…' if len(ans) > 420 else ''}",
            f"- **Category:** {', '.join(f'{c} ({diagnose.CATEGORIES[c]})' for c in cat) or '–'}",
            f"- **Cause:** {cause}", f"- **Fix:** {fix}", f"- **Proof:** {proof}", ""]


def write_gallery(rec: dict) -> Path:
    ev, man = evaluate.load("eval.json"), evaluate.load("manual_review.json")
    qs = {q["id"]: q for q in datasets.questions()}
    fin = {v: evaluate.final(ev[v]["rows"], man.get(v, {})) for v in evaluate.VERSIONS}
    rows = {v: {r["id"]: r for r in ev[v]["rows"]} for v in evaluate.VERSIONS}
    sysmap = {"v1": "dense_base", "v2": "rrf_v2", "v3": "rrf_v2"}

    cand = rec.get("candidates_top20", {})

    def cats(v: str, i: int) -> list[str]:
        """Failure categories. \"Found\" means ALL correct chunks (for a question with two correct chunks, one missing is enough)."""
        r, q = rows[v][i], qs[i]
        gold = set(q["chunks"])
        final_ids = {t["id"] if isinstance(t, dict) else t for t in r["top"]}
        c_ids = set(cand.get(sysmap[v], {}).get(str(i), []))
        return diagnose.classify(answerable=bool(gold), correct=bool(fin[v][i]), said_nevim=bool(r["said_nevim"]), gold_in_final=gold <= final_ids,
                                 gold_in_candidates=gold <= (c_ids | final_ids), grounded=bool(r["judge"]["grounded"]))

    L = ["[Česky](cs/failure-gallery.md)", "", "# Failure gallery", "", ABBREVIATIONS, "",
         "Real failures from the measurements: input, expected and actual behaviour, where in the chain it arose, the cause, the fix and proof that the fix helped. "
         "The categories say WHERE the chain broke, so it is clear what to fix:", ""]
    L += [f"- **{k}** – {v}" for k, v in diagnose.CATEGORIES.items()]
    L += ["", "## How many failures in which category", "",
          "| Version | Wrong answers | A not found | B dropped | C misread | E should have refused | F needless \"I don't know\" |", "|---|---|---|---|---|---|---|"]
    for v in evaluate.VERSIONS:
        bad = [i for i in fin[v] if not fin[v][i]]
        cnt = {c: sum(diagnose.primary(cats(v, i)) == c for i in bad) for c in "ABCEF"}
        L.append(f"| {v} | {len(bad)} of {len(fin[v])} | {cnt['A']} | {cnt['B']} | {cnt['C']} | {cnt['E']} | {cnt['F']} |")
    L += ["", "Category D (claim without support) is counted separately, because it can be added even to a correct answer: see the number-check section in [benchmark-results.md](benchmark-results.md). "
          "There is one primary cause per answer here (A before B before C before E and F). \"Found\" means all correct chunks. For v1 and v2 (which have no selection from 20), B means \"it was among the top 20, but the cut to 5 dropped it\". "
          "The v1 and v2 candidates come from a replay (v2 originally used a rewrite with hidden reasoning, so they may differ slightly from the measurement at the time).", "",
          "## Fixed failures (v2 → v3)", ""]
    for i in rec["transitions"]["v2->v3"]["fixed"]:
        cause, fix = FIXES.get(i, ("see the note in `data/manual_review.json`", "v3"))
        note = man.get("v2", {}).get(str(i), {}).get("note", "")
        c = cats("v2", i)
        L += _case(f"Question {i}: {qs[i]['q']}", rows["v2"][i], qs[i]["gold"], c, cause + (f" Manual note: {note}" if note else ""), fix,
                   f"correct in v3 (manual review), v2 → v3 regressed 0 questions out of {rec['n']['questions']}.")
    L += ["## Regressions: v1 → v2", "",
          "Fixing one thing broke another. Two questions that v1 got right failed in v2. That is why everything is measured again after every change, not only the fixed question.", ""]
    for i in rec["transitions"]["v1->v2"]["regressed"]:
        note = man.get("v2", {}).get(str(i), {}).get("note", "")
        L += _case(f"Question {i}: {qs[i]['q']}", rows["v2"][i], qs[i]["gold"], cats("v2", i), note or "see `data/manual_review.json`",
                   "fixed in v3 (the same question is correct in v3)", f"v3: {'correct' if fin['v3'][i] else 'error'}.")
    L += ["## Regression during v3 development (v3.0 → fix)", "",
          "A detailed analysis is in the incident: [2026-10-06 regression in rest between shifts](incidents/2026-10-06-regrese-odpocinek.md).", ""]

    # open failures: sample questions on the website
    site = json.loads((ROOT / "site" / "data.json").read_text(encoding="utf-8"))
    L += ["## Open failures (not fixed yet)", "",
          "Of the 16 sample questions on the website, two are wrong. I leave them visible on the website too. Neither is in the test sets, so nobody tuned for them.", ""]
    for q in site["questions"]:
        rv = q.get("review")
        if rv and not rv.get("ok"):
            kind = "hledání" if "hledání" in rv["note"] else "čtení"   # the review notes are Czech data: "hledání" = retrieval, "čtení" = reading
            cat = ["A"] if kind == "hledání" else ["C"]
            fix = ("The cause is measured, the fix is not deployed yet: see [ADR-004](decisions/ADR-004-prepis-a-bm25-otevrena-otazka.md). The question rewrite sent retrieval elsewhere "
                   "(the correct paragraph ranks 12th by the meaning of the original question, 219th by the rewritten one, and 106th in BM25 over the rewrite). A proposed fix must be tried on a new set, not on this question."
                   if kind == "hledání" else
                   "No fix yet. Proposal: a prompt rule for \"before / after termination\" conditions and a test on more questions with an inverted condition; verify on a new set.")
            L += _case(f"Web: {q['q']}", {"q": q["q"], "answer": q["answer"]}, WEB_EXPECTED.get(q["q"], "see the note in the cause"), cat, rv["note"], fix,
                       "none (the fix has not been made yet; I am not claiming it is fixed).")
    out = DOCS / "failure-gallery.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    rec = latest_run()
