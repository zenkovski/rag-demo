# -*- coding: utf-8 -*-
"""REST API nad vrstvou služby (tools/service.py). Žádná vlastní logika hledání: jen HTTP, klíč, limity a chyby.

  uvicorn api:app --app-dir tools --port 8000        # dokumentace na http://localhost:8000/docs

Klíče: proměnná prostředí RAG_API_KEYS (víc klíčů oddělit čárkou), posílají se v hlavičce X-API-Key.
RAG_OFFLINE=1 = jen uložené výsledky z data/*cache*, nikdy placené volání (výchozí v docker-compose.yml).
"""
from __future__ import annotations

import logging
import os
import re
import secrets
import uuid
from typing import Any

from fastapi import Depends, FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from fastapi.security import APIKeyHeader
from pydantic import BaseModel, Field
from starlette.exceptions import HTTPException as StarletteHTTPException

import service
from service import Law, Mode

MAX_BODY_BYTES = 16_384
log = logging.getLogger("rag.api")

app = FastAPI(
    title="Czech Labour Law Knowledge API",
    version="1.0.0",
    description="Hybrid retrieval (e5-large + BM25 + RRF + LLM pick) over 4 Czech labour laws, 2,475 paragraphs. "
                "Every passage has a paragraph ID such as `ZP § 52 odst. 1`. Answers are generated by an LLM and are not legal advice.",
)


# ---------- chyby: vždy {"error": {code, message, request_id, details}} ----------
def error(request: Request, status: int, code: str, message: str, details: dict | None = None) -> JSONResponse:
    rid = getattr(request.state, "request_id", None)
    return JSONResponse(status_code=status, headers={"X-Request-ID": rid or ""},
                        content={"error": {"code": code, "message": message, "request_id": rid, "details": details or {}}})


STATUS = {service.InvalidInput: 422, service.NotFound: 404, service.ProviderUnavailable: 503, service.ProviderTimeout: 504}


@app.exception_handler(service.ServiceError)
async def service_error(request: Request, e: service.ServiceError) -> JSONResponse:
    return error(request, STATUS.get(type(e), 500), e.code, e.message, e.details)


@app.exception_handler(RequestValidationError)
async def validation_error(request: Request, e: RequestValidationError) -> JSONResponse:
    fields = [{"field": ".".join(str(x) for x in err["loc"][1:]), "message": err["msg"]} for err in e.errors()]
    return error(request, 422, "invalid_input", "request does not match the schema", {"fields": fields})


@app.exception_handler(StarletteHTTPException)
async def http_error(request: Request, e: StarletteHTTPException) -> JSONResponse:
    codes = {400: "bad_request", 404: "not_found", 405: "method_not_allowed"}
    return error(request, e.status_code, codes.get(e.status_code, "http_error"), str(e.detail))


@app.exception_handler(Exception)
async def unexpected(request: Request, e: Exception) -> JSONResponse:
    log.exception("unhandled error, request %s", getattr(request.state, "request_id", None))
    return error(request, 500, "internal_error", "unexpected server error")     # bez stack trace ven


# ---------- ID požadavku a strop velikosti těla ----------
RID = re.compile(r"^[A-Za-z0-9._-]{1,64}$")


@app.middleware("http")
async def request_id_and_size(request: Request, call_next: Any) -> Any:
    incoming = request.headers.get("x-request-id", "")
    request.state.request_id = incoming if RID.match(incoming) else uuid.uuid4().hex
    if int(request.headers.get("content-length") or 0) > MAX_BODY_BYTES:
        return error(request, 413, "payload_too_large", f"request body over {MAX_BODY_BYTES} bytes")
    response = await call_next(request)
    response.headers["X-Request-ID"] = request.state.request_id
    return response


# ---------- klíč ----------
api_key_header = APIKeyHeader(name="X-API-Key", auto_error=False, description="Set RAG_API_KEYS on the server")


class Unauthorized(service.ServiceError):
    code = "unauthorized"


STATUS[Unauthorized] = 401


def require_key(key: str | None = Depends(api_key_header)) -> None:
    """Klíče se čtou při každém požadavku (změna proměnné nevyžaduje restart v testech). Porovnání v konstantním čase."""
    allowed = [k.strip() for k in os.environ.get("RAG_API_KEYS", "").split(",") if k.strip()]
    if not key or not any(secrets.compare_digest(key, k) for k in allowed):
        raise Unauthorized("missing or invalid X-API-Key" + ("" if allowed else " (server has no RAG_API_KEYS configured)"))


# ---------- požadavky ----------
class SearchRequest(BaseModel):
    query: str = Field(min_length=service.MIN_QUERY, max_length=service.MAX_QUERY, examples=["Kolik dní dovolené mi náleží?"])
    k: int = Field(5, ge=1, le=service.MAX_K, description="Number of passages (mode=full returns at most 5)")
    mode: Mode = Field("fast", description="fast = embeddings only, no LLM (recall@5 0.857); full = v3 with LLM rewrite and pick (recall@5 0.987)")
    laws: list[Law] | None = Field(None, max_length=4, description="Restrict results to these laws")


class AskRequest(BaseModel):
    question: str = Field(min_length=service.MIN_QUERY, max_length=service.MAX_QUERY, examples=["Jaká je délka výpovědní doby?"])
    laws: list[Law] | None = Field(None, max_length=4)


class ErrorBody(BaseModel):
    code: str
    message: str
    request_id: str | None
    details: dict


class ErrorResponse(BaseModel):
    error: ErrorBody


ERRORS: dict[int | str, dict[str, Any]] = {s: {"model": ErrorResponse} for s in (401, 404, 413, 422, 503, 504)}


# ---------- endpointy (sync: FastAPI je pustí ve vlákně, služba volá síť blokujícím způsobem) ----------
@app.get("/health", tags=["ops"])
def health() -> dict[str, Any]:
    """Bez klíče a bez volání sítě."""
    return service.health()


@app.post("/api/v1/search", response_model=service.SearchResult, responses=ERRORS, dependencies=[Depends(require_key)], tags=["knowledge"])
def search(body: SearchRequest) -> service.SearchResult:
    """Ranked law passages with paragraph IDs and scores. mode=fast needs no LLM."""
    return service.search(body.query, k=body.k, mode=body.mode, laws=body.laws, timeout=service.TIMEOUT_S)


@app.post("/api/v1/ask", response_model=service.AskResult, responses=ERRORS, dependencies=[Depends(require_key)], tags=["knowledge"])
def ask(body: AskRequest) -> service.AskResult:
    """Answer with structured citations and evidence_status. Uses 3 LLM calls unless the answer is cached."""
    return service.ask(body.question, laws=body.laws, timeout=service.TIMEOUT_S)


@app.get("/api/v1/documents/{doc_id}", response_model=service.Document, responses=ERRORS, dependencies=[Depends(require_key)], tags=["knowledge"])
def get_document(doc_id: str) -> service.Document:
    """Full text and metadata of one passage. URL-encode the ID: `ZP%20%C2%A7%2051%20odst.%202`."""
    return service.get_document(doc_id)
